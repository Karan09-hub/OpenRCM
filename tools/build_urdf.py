"""Generate the Dobot CR5 + straight instrument URDF for OpenRCM.

Outputs:
    urdf/cr5_rcm.urdf: straight surgical-style instrument (flange adapter + shaft + tip)
    meshes/obj/rcm_*.stl: generated visual & collision meshes for the instrument

Run:
    python tools/build_urdf.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import numpy as onp
import trimesh

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from openrcm import instrument, paths  # noqa: E402

INSTRUMENT_PARTS = (  # (name, rgba) -> meshes/obj/rcm_<name>.stl
    ("adapter", "0.24 0.24 0.25 1"),
    ("shaft", "0.75 0.76 0.78 1"),
    ("tip", "1.0 0.47 0.0 1"),
)

INSTRUMENT_LINKS = """
  <!-- Straight instrument on the flange; its shaft axis is the Link6 +z axis. -->
  <link name="instrument">
    <inertial>
      <origin xyz="0 0 0.05" rpy="0 0 0" />
      <mass value="0.3" />
      <inertia ixx="0.0005" ixy="0" ixz="0" iyy="0.0005" iyz="0" izz="0.0001" />
    </inertial>
{visuals}
    <collision>
      <geometry><mesh filename="../meshes/obj/rcm_instrument_collision.stl" /></geometry>
    </collision>
  </link>
  <joint name="instrument_mount" type="fixed">
    <origin xyz="0 0 0" rpy="0 0 0" />
    <parent link="Link6" />
    <child link="instrument" />
  </joint>

  <link name="tool_tip" />
  <joint name="tool_tip_joint" type="fixed">
    <origin xyz="0 0 {tool_length:.4f}" rpy="0 0 0" />
    <parent link="instrument" />
    <child link="tool_tip" />
  </joint>
"""

INSTRUMENT_VISUAL = """    <visual>
      <geometry><mesh filename="../meshes/obj/rcm_{name}.stl" /></geometry>
      <material name="instrument_{name}"><color rgba="{rgba}" /></material>
    </visual>"""


def export_instrument_mesh() -> str:
    """Adapter, shaft and tip as STL files; returns the URDF <visual> blocks for them."""
    i = instrument
    adapter = trimesh.creation.cylinder(radius=i.ADAPTER_RADIUS, height=i.ADAPTER_LENGTH, sections=32)
    adapter.apply_translation([0, 0, i.ADAPTER_LENGTH / 2])
    shaft = trimesh.creation.cylinder(radius=i.SHAFT_RADIUS, height=i.SHAFT_LENGTH, sections=32)
    shaft.apply_translation([0, 0, i.ADAPTER_LENGTH + i.SHAFT_LENGTH / 2])
    tip = trimesh.creation.cone(radius=i.SHAFT_RADIUS, height=i.TIP_LENGTH, sections=32)
    tip.apply_translation([0, 0, i.ADAPTER_LENGTH + i.SHAFT_LENGTH])
    parts = {"adapter": adapter, "shaft": shaft, "tip": tip}
    paths.OBJ_DIR.mkdir(parents=True, exist_ok=True)
    for name, mesh in parts.items():
        mesh.export(paths.OBJ_DIR / f"rcm_{name}.stl")
    trimesh.util.concatenate(list(parts.values())).export(paths.OBJ_DIR / "rcm_instrument_collision.stl")
    return "\n".join(INSTRUMENT_VISUAL.format(name=n, rgba=c) for n, c in INSTRUMENT_PARTS)


def base_urdf() -> str:
    """The arm alone: the xacro with Gazebo tags removed, relative meshes, real speed limits."""
    src = paths.XACRO.read_text()
    src = re.sub(r"\s*<!-- Disable physics.*?</robot>", "\n\n</robot>", src, flags=re.S)
    src = src.replace(' xmlns:xacro="http://ros.org/wiki/xacro"', "")
    src = src.replace("package://dobot_description/meshes/cr5/", "../Assets/")
    src = src.replace('effort="300" velocity="100"', 'effort="300" velocity="3.14"')
    names = {"0 0 0 1": "cr5_black", "1 1 1 1": "cr5_white"}
    return re.sub(
        r'<material\s+name="">(\s*<color rgba="([^"]+)" />)',
        lambda m: f'<material name="{names.get(m.group(2), "cr5_" + m.group(2).replace(" ", "_"))}">{m.group(1)}',
        src,
    )


def write_urdf(path: Path, src: str, tool_links: str, tool_name: str) -> None:
    src = src.replace("\n</robot>", tool_links + "\n</robot>")
    header = (
        "<!-- Generated by tools/build_urdf.py from Assets/cr5_robot.xacro. Do not edit.\n"
        "     Changes: Gazebo tags removed, mesh paths relative, velocity limits 3.14 rad/s,\n"
        f"     {tool_name} links added. -->\n"
    )
    src = src.replace('<?xml version="1.0"?>\n', '<?xml version="1.0"?>\n' + header, 1)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(src)


def main() -> None:
    src = base_urdf()
    visuals = export_instrument_mesh()
    tool = INSTRUMENT_LINKS.format(visuals=visuals, tool_length=instrument.TOOL_LENGTH)
    write_urdf(paths.URDF, src, tool, "Instrument + tool_tip")
    print(f"Wrote {paths.URDF} (tool tip {instrument.TOOL_LENGTH * 1000:.0f} mm from flange)")


if __name__ == "__main__":
    main()
